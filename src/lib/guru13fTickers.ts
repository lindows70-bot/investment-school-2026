// 법인마다 다른 표기를 한 모양으로 — 튜더식 접미사(' - US' · ' - US ADR' · ' - US ETP' · ' - C Shares') · 문장부호 · 법인 꼬리말(INC · CORP · LTD · PLC …)을 걷어 낸다.
//   걷어 낸 '알맹이'가 **통째로** 같을 때만 같은 회사로 본다(앞부분 일치 금지 — 'BLOCK'(블록) 과 'BLOCK H & R'(H&R 블록) 은 다른 회사).
export function coreName(name: string): string {
  return name.toUpperCase()
    .replace(/\s+-\s+(US(\s+\w+)?|[A-C](\s+SHARES)?)\s*$/, '')
    .replace(/\/THE\b/g, ' ').replace(/[.,']/g, ' ')
    .replace(/\b(INC|INCORPORATED|CORP|CORPORATION|CO|COMPANY|LTD|PLC|COM|NEW|DEL|SWITZ|THE|CL [A-C]|CLASS [A-C])\b/g, ' ')
    .replace(/\s+/g, ' ').trim()
}
const CORE_TO_TICKER: Record<string, string> = {}
for (const k of Object.keys(NAME_TO_TICKER)) { const c = coreName(k); if (c && !(c in CORE_TO_TICKER)) CORE_TO_TICKER[c] = NAME_TO_TICKER[k] }

// 발행사명 정규화 매칭 — 정확 일치 우선, 그 다음 접미사(NEW·CL A 등) 제거 후, 마지막으로 알맹이 대조
export function issuerToTicker(name: string): string | null {
  const u = name.toUpperCase().trim()
  if (NAME_TO_TICKER[u]) return NAME_TO_TICKER[u]
  const stripped = u.replace(/\s+(NEW|CL [A-C]|CLASS [A-C]|COM|DEL|SWITZ)\b/g, '').replace(/\s+/g, ' ').trim()
  return NAME_TO_TICKER[stripped] ?? CORE_TO_TICKER[coreName(u)] ?? null
}
